#!/usr/bin/env node
// Read-only deployment checks. No browser state, answers, notes, or POSTs.
// Run manually after deployment; intentionally excluded from the CI test list.
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';

const BASE = '/assets/personality/v5/';
const LEGACY_BASE = '/assets/personality/v1/';
const PUBLIC_ORIGIN = 'https://engmanager.xyz';
const STEPS = ['prepare', 'test', 'review', 'report', 'share', 'library'];
const REQUIRED = ['app.mjs', 'style.css', 'bank.mjs', 'core.mjs', 'store.mjs', 'share.mjs',
  'report-content.mjs', 'report.mjs', 'charts.mjs', 'charts.css', 'pdf.mjs', 'offline.mjs', 'sw.js',
  'enhancement.mjs', 'enhancement-share.mjs', 'reflection-ui.mjs', 'ai-cache-config.mjs',
  'vendor/idb.mjs', 'vendor/pdf-lib/pdf-lib.min.mjs', 'vendor/pdf-lib/fontkit.min.mjs', 'vendor/pdf-lib/pako.mjs'];
const HASH = /^[a-f0-9]{64}$/;
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const requireThat = (condition, message) => {if (!condition) throw new Error(message);};
function exactKeys(value, keys, label) {
  requireThat(value && typeof value === 'object' && !Array.isArray(value) &&
    Object.keys(value).length === keys.length && keys.every(key => Object.hasOwn(value, key)), `Invalid ${label} fields.`);
}

// Parse only the JSON literal in the generated registry. Remote JS is never
// imported, evaluated, or run in a VM. The wrapper must match its known grammar.
function registryData(source) {
  const match = /^\/\/ Generated by scripts\/personality-release\.mjs; do not edit hashes by hand\.\r?\nconst data = (\{[\s\S]*\});\r?\nfunction freeze\(value\) \{ if \(value && typeof value === "object"\) \{ Object\.values\(value\)\.forEach\(freeze\); Object\.freeze\(value\); \} return value; \}\r?\nexport const RELEASE = freeze\(data\);\r?\n?$/.exec(source);
  requireThat(match, 'Release registry does not match the expected JSON-only wrapper.');
  return JSON.parse(match[1]);
}

export function parseRegistry(source) {
  const data = registryData(source);
  exactKeys(data, ['v', 'releases', 'blockIds', 'ready', 'assets'], 'release registry');
  requireThat(data.v === 1 && data.ready === true, 'Release is not a complete supported v1 registry.');
  exactKeys(data.releases, ['instruments', 'content', 'scoring', 'template', 'order'], 'release identities');
  const identities = ['ipip-neo-120', 'onet-mini-ip-30', 'twivi-20'];
  requireThat(Array.isArray(data.releases.instruments) && data.releases.instruments.length === 3 &&
    data.releases.instruments.every((entry, index) => Array.isArray(entry) && entry.length === 3 &&
      entry[0] === identities[index] && typeof entry[1] === 'string' && entry[1].length <= 100 && HASH.test(entry[2])), 'Invalid instrument release identities.');
  for (const key of ['content', 'scoring', 'template', 'order']) {
    const entry = data.releases[key];
    requireThat(Array.isArray(entry) && entry.length === 2 && typeof entry[0] === 'string' && entry[0].length <= 100 && HASH.test(entry[1]), `Invalid ${key} release identity.`);
  }
  requireThat(Array.isArray(data.blockIds) && data.blockIds.length <= 12 && new Set(data.blockIds).size === data.blockIds.length &&
    data.blockIds.every(id => typeof id === 'string' && /^[a-z0-9-]{1,80}$/.test(id)), 'Invalid report block IDs.');
  requireThat(data.assets && typeof data.assets === 'object' && !Array.isArray(data.assets), 'Invalid asset registry.');
  const entries = Object.entries(data.assets);
  requireThat(entries.length >= REQUIRED.length && entries.length <= 128, 'Unexpected asset count.');
  for (const [name, hash] of entries) {
    requireThat(name.length <= 180 && /^[A-Za-z0-9][A-Za-z0-9._-]*(?:\/[A-Za-z0-9][A-Za-z0-9._-]*)*$/.test(name) &&
      !name.split('/').some(part => part === '.' || part === '..') && typeof hash === 'string' && HASH.test(hash), 'Unsafe asset path or invalid digest.');
  }
  requireThat(REQUIRED.every(name => Object.hasOwn(data.assets, name)), 'Required public app files are absent from the registry.');
  return data;
}

export function parsePresentationRegistry(source) {
  const data = registryData(source);
  const presentations = {2: 'prompt-evidence-v2', 3: 'portrait-pdf-v3', 4: 'workplace-report-v4', 5: 'portrait-studio-v5'};
  requireThat(Number.isInteger(data.v) && Object.hasOwn(presentations, data.v) && data.presentation === presentations[data.v] && data.ready === true, 'Unsupported or incomplete presentation release.');
  exactKeys(data, ['v', 'presentation', 'legacy', ...(data.v >= 4 ? ['previousReleases'] : data.v === 3 ? ['previous'] : []), 'releases', 'ready', 'assets'], 'presentation registry');
  const currentBase = `/assets/personality/v${data.v}/`;
  if (data.v === 3) {
    exactKeys(data.previous, ['root', 'manifestSha256', 'releaseDigest'], 'previous presentation reference');
    requireThat(data.previous.root === '/assets/personality/v2/' && HASH.test(data.previous.manifestSha256) && HASH.test(data.previous.releaseDigest), 'Invalid previous presentation reference.');
  } else if (data.v >= 4) {
    requireThat(Array.isArray(data.previousReleases) && data.previousReleases.length === data.v - 2, 'Invalid retained presentation releases.');
    for (const [index, release] of data.previousReleases.entries()) {
      exactKeys(release, ['v', 'root', 'manifestSha256', 'releaseDigest'], 'retained presentation reference');
      requireThat(release.v === data.v - 1 - index && release.root === `/assets/personality/v${release.v}/` && HASH.test(release.manifestSha256) && HASH.test(release.releaseDigest), 'Invalid retained presentation reference.');
    }
  }
  exactKeys(data.legacy, ['root', 'manifestSha256', 'releaseDigest'], 'legacy release reference');
  requireThat(data.legacy.root === LEGACY_BASE && HASH.test(data.legacy.manifestSha256) && HASH.test(data.legacy.releaseDigest), 'Invalid legacy release reference.');
  requireThat(data.assets && typeof data.assets === 'object' && !Array.isArray(data.assets), 'Invalid presentation assets.');
  const entries = Object.entries(data.assets);
  requireThat(entries.length >= REQUIRED.length && entries.length <= (data.v === 5 ? 256 : 160), 'Unexpected presentation asset count.');
  for (const [name, hash] of entries) {
    requireThat(name.length <= 220 && /^\/assets\/personality\/v[12345]\/[A-Za-z0-9][A-Za-z0-9._-]*(?:\/[A-Za-z0-9][A-Za-z0-9._-]*)*$/.test(name) &&
      !name.split('/').some(part => part === '.' || part === '..') && Number(name.match(/\/v([1-5])\//)?.[1]) <= data.v &&
      typeof hash === 'string' && HASH.test(hash), 'Unsafe presentation asset path or invalid digest.');
  }
  requireThat(['app.mjs', 'bootstrap.mjs', ...(data.v === 5 ? ['studio.mjs', 'studio-model.mjs', 'studio-view.mjs', 'studio-kit.mjs', 'studio-store.mjs'] : ['report.mjs', 'report-kit.mjs', 'report-kit-ui.mjs', 'report-kit-store.mjs']), 'style.css', 'offline.mjs', 'sw.js', 'release-format.mjs'].every(name => Object.hasOwn(data.assets, currentBase + name)), 'Missing current presentation assets.');
  requireThat(REQUIRED.every(name => Object.hasOwn(data.assets, LEGACY_BASE + name)), 'Missing legacy public assets.');
  return data;
}

function options(args) {
  let origin = PUBLIC_ORIGIN, expectLocal = false;
  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    if (arg === '--expect-local') expectLocal = true;
    else if (arg === '--origin') {origin = args[++index]; requireThat(origin, '--origin needs a URL.');}
    else if (arg.startsWith('--origin=')) origin = arg.slice(9);
    else throw new Error(`Unknown argument: ${arg}`);
  }
  const url = new URL(origin);
  requireThat(!url.username && !url.password && url.pathname === '/' && !url.search && !url.hash, 'Supply only an origin, without credentials, a path, query, or fragment.');
  requireThat(url.protocol === 'https:' || (url.protocol === 'http:' && ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)), 'HTTPS is required except for a loopback test server.');
  return {origin: url.origin, expectLocal};
}

async function request(origin, path, {status = 200, limit = 2 * 1024 * 1024} = {}) {
  const url = new URL(path, origin);
  requireThat(url.origin === origin && !url.search && !url.hash, 'Only clean same-origin public URLs are permitted.');
  const response = await fetch(url, {method: 'GET', redirect: 'manual', credentials: 'omit', referrerPolicy: 'no-referrer',
    headers: {'Cache-Control': 'no-cache'}, signal: AbortSignal.timeout(20000)});
  if (response.status !== status) {
    await response.body?.cancel();
    throw new Error(`${path}: HTTP ${response.status}, expected ${status}.`);
  }
  const reader = response.body?.getReader(), chunks = []; let size = 0;
  try {
    if (reader) while (true) {
      const {done, value} = await reader.read(); if (done) break;
      size += value.byteLength; requireThat(size <= limit, `${path}: body exceeds ${limit} bytes.`); chunks.push(value);
    }
  } catch (error) {await reader?.cancel().catch(() => {}); throw error;}
  return {response, bytes: Buffer.concat(chunks, size)};
}

function privacy(response, {document = false, noStore = true} = {}) {
  const headers = response.headers;
  requireThat(headers.get('referrer-policy') === 'no-referrer', 'Missing no-referrer policy.');
  requireThat(headers.get('x-content-type-options') === 'nosniff', 'Missing nosniff policy.');
  requireThat(!headers.has('content-security-policy-report-only'), 'Unexpected report-only CSP on the private boundary.');
  const directives = new Map();
  for (const value of (headers.get('content-security-policy') || '').split(';').map(part => part.trim()).filter(Boolean)) {
    const [key, ...tokens] = value.split(/\s+/);
    requireThat(!directives.has(key), `Duplicate CSP directive: ${key}`); directives.set(key, tokens);
  }
  for (const [name, expected] of Object.entries({'default-src': ["'none'"], 'connect-src': ["'self'"],
    'base-uri': ["'none'"], 'object-src': ["'none'"], 'frame-ancestors': ["'none'"], 'form-action': ["'none'"], 'worker-src': ["'self'"]})) {
    requireThat(JSON.stringify(directives.get(name)) === JSON.stringify(expected), `Unexpected ${name} CSP.`);
  }
  const scripts = directives.get('script-src') || [];
  requireThat(scripts.includes("'self'") && scripts.every(value => ["'self'", "'wasm-unsafe-eval'"].includes(value)), 'Scripts allow an unexpected source or execution mode.');
  requireThat(!directives.has('report-uri') && !directives.has('report-to'), 'Unexpected CSP reporting endpoint.');
  if (document) {
    requireThat(headers.get('content-type')?.startsWith('text/html'), 'Document MIME type is not HTML.');
    requireThat(headers.get('cache-control')?.split(',').map(value => value.trim()).includes('no-transform'), 'Document permits edge HTML transformation or injected analytics.');
    if (noStore) {
      requireThat(headers.get('cache-control')?.split(',').map(value => value.trim()).includes('no-store'), 'Document is missing Cache-Control: no-store.');
      for (const name of ['cdn-cache-control', 'cloudflare-cdn-cache-control']) {
        requireThat(!headers.has(name) || headers.get(name).includes('no-store'), `Unexpected cacheable ${name}.`);
      }
    }
    requireThat(!headers.has('set-cookie'), 'Public assessment document unexpectedly sets a cookie.');
    requireThat(headers.get('x-frame-options') === 'DENY', 'Missing frame isolation.');
  }
}

function attributes(text) {
  return Object.fromEntries([...text.matchAll(/([\w:-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g)].map(match => [match[1].toLowerCase(), match[2] ?? match[3]]));
}
function metadata(html, path, route) {
  const metas = [...html.matchAll(/<meta\b([^>]*)>/gi)].map(match => attributes(match[1]));
  const links = [...html.matchAll(/<link\b([^>]*)>/gi)].map(match => attributes(match[1]));
  const meta = key => metas.find(tag => tag.name === key || tag.property === key)?.content;
  requireThat(html.includes(`data-personality-route="${route}"`) && html.includes('id="personality-app"'), 'Wrong reduced shell or route marker.');
  requireThat(/<title>[^<]*The Big Six-Seven<\/title>/.test(html), 'Missing page title.');
  requireThat(meta('referrer') === 'no-referrer', 'Missing referrer metadata.');
  requireThat(meta('robots') === (route === 'article' ? 'index, follow' : 'noindex, nofollow'), 'Unexpected indexing metadata.');
  requireThat(meta('description')?.length > 50, 'Missing page description.');
  requireThat(links.find(tag => tag.rel === 'canonical')?.href === PUBLIC_ORIGIN + path && meta('og:url') === PUBLIC_ORIGIN + path, 'Canonical or Open Graph URL is incorrect.');
  requireThat(meta('og:image') === PUBLIC_ORIGIN + '/assets/og/article-big-personality.jpg' && meta('og:image:width') === '1200' && meta('og:image:height') === '630', 'Generic social-card metadata is incorrect.');
  requireThat(meta('og:title') === 'The Big Six-Seven' && meta('twitter:card') === 'summary_large_image', 'Missing social title or card metadata.');
  const scripts = [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)];
  requireThat(scripts.length === 1 && attributes(scripts[0][1]).type === 'module' &&
    attributes(scripts[0][1]).src === BASE + 'bootstrap.mjs' && !scripts[0][2].trim(), 'Unexpected script, telemetry, or inline execution in reduced shell.');
  requireThat(['style.css', 'charts.css'].every(name => links.some(tag => tag.rel === 'stylesheet' && tag.href === LEGACY_BASE + name)), 'Required local styles are missing.');
  requireThat(links.some(tag => tag.id === 'personality-presentation-style' && tag.href === BASE + 'style.css' && tag.media === 'not all'), 'Current presentation style is not gated from legacy snapshots.');
  requireThat(!/__engNav|speculationrules|fonts\.googleapis|experiences\.js|rum\.js/.test(html), 'Global navigation, remote fonts, or monitoring leaked into the reduced shell.');
}

export async function smoke({origin, expectLocal = false}) {
  const results = [];
  async function check(label, run) {
    try {const detail = await run(); results.push({label, ok: true, detail}); return detail;}
    catch (error) {results.push({label, ok: false, error: error.message}); return null;}
  }
  await Promise.all([['/articles/big-personality', 'article'], ...STEPS.map(step => [`/personality/${step}`, step])].map(([path, route]) => check(path, async () => {
    const {response, bytes} = await request(origin, path, {limit: 1024 * 1024});
    // The indexed introduction contains only static public prose and can use
    // the blog's public HTML cache. Questionnaire documents must be no-store.
    privacy(response, {document: true, noStore: route !== 'article'}); metadata(bytes.toString('utf8'), path, route);
    return `200 · reduced shell and canonical metadata${route === 'article' ? ' · public article' : ' · no-store'}`;
  })));
  await check('/personality redirect', async () => {
    const {response} = await request(origin, '/personality', {status: 307});
    requireThat(response.headers.get('location') === '/personality/prepare', 'Wrong entry redirect.');
    requireThat(response.headers.get('cache-control') === 'no-store', 'Entry redirect is cacheable.');
    return '307 → /personality/prepare';
  });
  await check('Unknown route remains 404', async () => {
    const {response, bytes} = await request(origin, '/personality/smoke-unknown-route', {status: 404});
    privacy(response, {document: true}); requireThat(bytes.toString().includes('data-personality-route="not-found"'), 'Unknown route did not use the private 404 shell.');
    return '404 · private document boundary';
  });
  let release;
  await check('Release registry', async () => {
    const {response, bytes} = await request(origin, BASE + 'release.mjs', {limit: 256 * 1024});
    privacy(response);
    requireThat(/javascript/.test(response.headers.get('content-type') || ''), 'Registry MIME type is not JavaScript.');
    release = parsePresentationRegistry(bytes.toString('utf8'));
    requireThat(release.v === 5, 'Current presentation must be v5.');
    if (expectLocal) {
      const local = await readFile(new URL('../website/assets/personality/v5/release.mjs', import.meta.url));
      requireThat(bytes.equals(local), `Deployed registry differs from local bytes (remote ${digest(bytes)}, local ${digest(local)}).`);
    }
    return `${Object.keys(release.assets).length} assets · sha256 ${digest(bytes)}${expectLocal ? ' · exact local match' : ''}`;
  });
  if (release) {
    await check('Frozen v1 release compatibility', async () => {
      const {bytes} = await request(origin, LEGACY_BASE + 'release.mjs', {limit: 256 * 1024});
      const legacy = parseRegistry(bytes.toString('utf8'));
      const lock = JSON.parse(await readFile(new URL('./personality-published-releases.json', import.meta.url), 'utf8'));
      requireThat(digest(bytes) === lock.roots.v1.manifestSha256 && digest(bytes) === release.legacy.manifestSha256, 'Published v1 manifest has changed.');
      requireThat(digest(JSON.stringify(legacy)) === release.legacy.releaseDigest, 'Legacy installation digest changed.');
      requireThat(JSON.stringify(legacy.releases) === JSON.stringify(release.releases), 'Scientific identities changed in the presentation release.');
      for (const [name, hash] of Object.entries(legacy.assets)) requireThat(release.assets[LEGACY_BASE + name] === hash, 'A legacy asset is missing or changed.');
      return 'Original manifest, scientific identities, and all original asset hashes retained';
    });
    for (const reference of release.previousReleases) {
      await check(`Frozen v${reference.v} presentation compatibility`, async () => {
        const {bytes} = await request(origin, reference.root + 'release.mjs', {limit: 256 * 1024});
        const previous = parsePresentationRegistry(bytes.toString('utf8'));
        const lock = JSON.parse(await readFile(new URL('./personality-published-releases.json', import.meta.url), 'utf8'));
        requireThat(previous.v === reference.v && digest(bytes) === (reference.v === 4 ? JSON.parse(await readFile(new URL('./personality-v4-frozen.json', import.meta.url), 'utf8')).files['release.mjs'] : lock.roots[`v${reference.v}`].manifestSha256) && digest(bytes) === reference.manifestSha256, `Published v${reference.v} manifest has changed.`);
        requireThat(digest(JSON.stringify(previous)) === reference.releaseDigest, 'Previous installation digest changed.');
        requireThat(release.assets[reference.root + 'release.mjs'] === digest(bytes), 'Previous manifest is missing from the offline release.');
        for (const [name, hash] of Object.entries(previous.assets)) requireThat(release.assets[name] === hash, 'A previous presentation asset is missing or changed.');
        return `Original v${reference.v} manifest and all its asset hashes retained`;
      });
    }
    // Exclude images, audio, fonts and the optional AI model/runtime installation.
    // Verify every small code/style/data file, including the required file list.
    const names = Object.keys(release.assets).filter(name => /\.(?:m?js|css|json)$/.test(name));
    let next = 0;
    await Promise.all(Array.from({length: Math.min(4, names.length)}, async () => {
      while (next < names.length) {
        const name = names[next++];
        await check(`SHA-256 ${name}`, async () => {
          const {response, bytes} = await request(origin, name); privacy(response);
          requireThat(digest(bytes) === release.assets[name], 'Published bytes do not match the release registry.');
          requireThat(!response.headers.get('content-type')?.includes('text/html'), 'An asset returned an HTML fallback.');
          return `${bytes.length.toLocaleString()} bytes`;
        });
      }
    }));
    await check('Scoped service worker', async () => {
      const {response, bytes} = await request(origin, '/personality/sw.js'); privacy(response);
      requireThat(response.headers.get('service-worker-allowed') === '/personality/', 'Incorrect service worker scope.');
      requireThat(response.headers.get('cache-control')?.includes('no-cache'), 'Worker update path may be stale.');
      requireThat(response.headers.get('cache-control')?.split(',').map(value => value.trim()).includes('no-store'), 'Worker update path permits storage despite the edge cache override.');
      for (const name of ['cdn-cache-control', 'cloudflare-cdn-cache-control']) {
        requireThat(!response.headers.has(name) || response.headers.get(name).includes('no-store'), `Worker has cacheable ${name}.`);
      }
      requireThat(digest(bytes) === release.assets[BASE + 'sw.js'], 'Worker route bytes differ from the pinned release.');
      return 'Exact release bytes · /personality/ scope';
    });
  }
  await check('Generic social-card image', async () => {
    const {response, bytes} = await request(origin, '/assets/og/article-big-personality.jpg', {limit: 300 * 1024});
    requireThat(response.headers.get('content-type')?.includes('image/jpeg') && bytes[0] === 255 && bytes[1] === 216, 'Social card is not a JPEG.');
    return `${bytes.length.toLocaleString()} bytes`;
  });
  return results;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--help') || process.argv.includes('-h')) {
    console.log('Usage: node scripts/personality-live-smoke.mjs [--origin=https://engmanager.xyz] [--expect-local]\n\nRead-only GET checks for seven routes, privacy headers, metadata, small public asset hashes, and the scoped worker.\n--expect-local additionally requires the deployed release.mjs bytes to match this checkout exactly.\nLarge media, fonts, optional AI binaries, user model weights, and browser behavior are not downloaded or tested.');
  } else {
    try {
      const config = options(process.argv.slice(2));
      console.log(`Checking ${config.origin}${config.expectLocal ? ' against this checkout' : ''} (public GET requests only)…`);
      const results = await smoke(config);
      for (const result of results) console.log(`${result.ok ? 'PASS' : 'FAIL'} ${result.label} · ${result.ok ? result.detail : result.error}`);
      const failed = results.filter(result => !result.ok).length;
      console.log(`${results.length - failed}/${results.length} checks passed. ${failed ? 'The expected release is not yet verified at this origin.' : 'Public deployment checks passed; browser and full model testing are separate.'}`);
      process.exitCode = failed ? 1 : 0;
    } catch (error) {console.error(`Live smoke: ${error.message}`); process.exitCode = 1;}
  }
}
