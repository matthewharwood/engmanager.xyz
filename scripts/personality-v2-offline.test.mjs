test('query navigation is never cached and offline replay reads the matching clean route', async () => {
  const env = environment();
  await env.install();
  const keysBefore = [...env.cacheMaps.values()].flatMap(map => [...map.keys()]);
  const query = '/personality/report?r=PRIVATE-SUMMARY';
  const online = await env.dispatch(query);
  assert((await online.text()).includes('?r=PRIVATE-SUMMARY'));
  assert.deepEqual([...env.cacheMaps.values()].flatMap(map => [...map.keys()]), keysBefore);
  env.controls.offline = true;
  const offline = await env.dispatch(query);
  assert.equal(await offline.text(), '<html>Public shell: /personality/report</html>');
  for (const route of ROUTES) assert.equal((await env.dispatch(route)).status, 200);
  assert(![...env.cacheMaps.values()].flatMap(map => [...map.keys()]).some(url => url.includes('PRIVATE-SUMMARY')));
});

