test('a frozen v1 installer receives its own digest after the complete compatible v2 installation', async () => {
  const env = environment();
  const old = await env.caches.open(`personality-v1-${LEGACY_DIGEST}`);
  await old.put('/personality/.offline-ready-v1', new Response('ready'));
  await old.put('/personality/report', new Response('original legacy shell'));
  const messages = await env.install({requestedDigest: LEGACY_DIGEST});
  assert.equal(messages.at(-1).type, 'OFFLINE_READY');
  assert(messages.every(message => message.releaseDigest === LEGACY_DIGEST));
  assert.equal(messages.at(-1).cacheName, `personality-v2-${env.digest}`);
  assert.equal(await (await old.match('/personality/report')).text(), 'original legacy shell');
  env.controls.offline = true;
  assert.equal(await (await env.dispatch(LEGACY_ROOT + 'app.mjs', {mode: 'cors'})).text(), 'immutable legacy application');
  assert.equal(await (await env.dispatch('/personality/report#s=legacy')).text(), '<html>Public shell: /personality/report</html>');
  const keys = [...env.cacheMaps.values()].flatMap(rows => [...rows.keys()]);
  assert(keys.every(url => !new URL(url).search && !new URL(url).hash));
});

test('the compatible worker can fall back to the exact retained v1 cache without modifying it', async () => {
  const env = environment();
  const old = await env.caches.open(`personality-v1-${LEGACY_DIGEST}`);
  await old.put('/personality/report', new Response('original legacy shell'));
  await old.put(LEGACY_ROOT + 'app.mjs', new Response('original legacy app'));
  env.controls.offline = true;
  assert.equal((await env.dispatch('/personality/report')).status, 503, 'Uncommitted legacy caches are ignored.');
  await old.put('/personality/.offline-ready-v1', new Response('ready'));
  const before = await old.keys();
  assert.equal(await (await env.dispatch('/personality/report?r=summary')).text(), 'original legacy shell');
  assert.equal(await (await env.dispatch(LEGACY_ROOT + 'app.mjs', {mode: 'cors'})).text(), 'original legacy app');
  assert.deepEqual((await old.keys()).map(item => item.url), before.map(item => item.url));
  assert.deepEqual(await env.caches.keys(), [`personality-v1-${LEGACY_DIGEST}`]);
});

test('client module is inert until clicked, registers exact module scope, and awaits ready acknowledgement', async () => {
  const {release} = fixture(), registrations = [], messages = [], progress = [];
  const worker = {state: 'activated', addEventListener() {}, removeEventListener() {}, postMessage(data, [port]) {
    messages.push(data);
    port.postMessage({type: 'OFFLINE_PROGRESS', releaseDigest: data.releaseDigest, completed: 1, total: 11});
    setTimeout(() => { port.postMessage({type: 'OFFLINE_READY', releaseDigest: data.releaseDigest, cacheName: 'installed', assets: 5, routes: 6}); port.close(); }, 10);
  }};
  const context = vm.createContext({__release: release, crypto: webcrypto, TextEncoder, Uint8Array, Date, Promise,
    isSecureContext: true, caches: {}, MessageChannel, setTimeout, clearTimeout,
    navigator: {serviceWorker: {async register(url, options) { registrations.push({url, options}); return {active: worker}; }}}});
  vm.runInContext(clientSource.replace(/^import[^\n]+\n/, 'const RELEASE = __release;\n').replace('export function installOffline', 'function installOffline'), context);
  assert.equal(registrations.length, 0);
  const first = context.installOffline({onProgress: value => progress.push(value)}), second = context.installOffline();
  assert.equal(first, second);
  const result = await first;
  assert.equal(result.routes, 6); assert.equal(result.assets, 5);
  assert.equal(registrations.length, 1); assert.equal(registrations[0].url, '/personality/sw.js');
  assert.equal(registrations[0].options.scope, '/personality/'); assert.equal(registrations[0].options.type, 'module');
  assert.equal(registrations[0].options.updateViaCache, 'none');
  assert.equal(messages.length, 1); assert.deepEqual(Object.keys(messages[0]), ['type', 'releaseDigest']);
  assert.equal(messages[0].releaseDigest, sha(JSON.stringify(release)));
  assert.equal(progress.length, 1);
});

test('waiting worker installs before takeover and client waits for activation after cache-ready', async () => {
  const {release} = fixture(), listeners = new Set();
  let listenCount = 0, enteredActivation;
  const activationPhase = new Promise(resolve => { enteredActivation = resolve; });
  const worker = {state: 'installed', addEventListener(type, listener) {
    listeners.add(listener); listenCount++; if (listenCount === 2) enteredActivation();
  }, removeEventListener(type, listener) { listeners.delete(listener); }, postMessage(data, [port]) {
    port.postMessage({type: 'OFFLINE_READY', releaseDigest: data.releaseDigest, cacheName: 'verified', assets: 5, routes: 6});
    port.close();
  }};
  const context = vm.createContext({__release: release, crypto: webcrypto, TextEncoder, Uint8Array, Date, Promise,
    isSecureContext: true, caches: {}, MessageChannel, setTimeout, clearTimeout,
    navigator: {serviceWorker: {async register() { return {waiting: worker, active: {state: 'activated'}}; }}}});
  vm.runInContext(clientSource.replace(/^import[^\n]+\n/, 'const RELEASE = __release;\n').replace('export function installOffline', 'function installOffline'), context);
  let settled = false;
  const installed = context.installOffline().then(result => { settled = true; return result; });
  await activationPhase;
  assert.equal(settled, false); assert.equal(worker.state, 'installed');
  worker.state = 'activated'; for (const listener of [...listeners]) listener();
  assert.equal((await installed).cacheName, 'verified'); assert.equal(settled, true);
});
