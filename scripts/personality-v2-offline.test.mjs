test('explicit install verifies all public assets, six clean shells, and separately pinned manifest bytes', async () => {
  const env = environment(), messages = await env.install();
  const ready = messages.at(-1);
  assert.equal(ready.type, 'OFFLINE_READY'); assert.equal(ready.routes, 6); assert.equal(ready.assets, 6);
  assert.equal(ready.cacheName, `personality-v2-${env.digest}`);
  assert.deepEqual(env.activations, ['skipWaiting']);
  const names = await env.caches.keys(); assert.deepEqual(names, [ready.cacheName]);
  const rows = env.cacheMaps.get(ready.cacheName);
  assert.equal(rows.size, 13); // Five hashed assets across both versions, manifest, six routes, marker.
  assert([...rows.keys()].every(url => !new URL(url).search && !new URL(url).hash));
  for (const route of ROUTES) assert(rows.has(ORIGIN + route));
  assert(rows.has(ORIGIN + ROOT + 'vendor/pdf-lib/pdf-lib.mjs'));
  assert(rows.has(ORIGIN + ROOT + 'fonts/report.ttf'));
  assert(env.requests.every(request => request.credentials === 'omit' && request.referrerPolicy === 'no-referrer' && request.cache === 'reload'));
  const before = env.requests.length;
  assert.equal((await env.install()).at(-1).type, 'OFFLINE_READY');
  assert.equal(env.requests.length, before, 'A complete immutable release need not be downloaded twice.');
});

