function releaseSource(release) {
  return '// Generated by scripts/personality-release.mjs; do not edit hashes by hand.\n' +
    'const data = ' + JSON.stringify(release, null, 2) + ';\n' +
    'function freeze(value) { if (value && typeof value === "object") { Object.values(value).forEach(freeze); Object.freeze(value); } return value; }\n' +
    'export const RELEASE = freeze(data);\n';
}

function fixture() {
  const bytes = new Map([
    ['bank.mjs', Buffer.from('export const publicBank = "170 public items";')],
    ['vendor/pdf-lib/pdf-lib.mjs', Buffer.from('export const PDFDocument = "public renderer";')],
    ['fonts/report.ttf', Buffer.from('public-font-bytes')],
    ['sw.js', Buffer.from(workerSource)],
  ]);
  const publicBytes = new Map([...bytes].map(([name, body]) => [ROOT + name, body]));
  publicBytes.set(LEGACY_ROOT + 'app.mjs', Buffer.from('immutable legacy application'));
  const release = {v: 2, ready: true, legacy: {root: LEGACY_ROOT, releaseDigest: LEGACY_DIGEST}, assets: Object.fromEntries([...publicBytes].map(([name, body]) => [name, sha(body)]))};
  return {bytes: publicBytes, release};
}

function environment(customRelease) {
  const {bytes, release: fixtureRelease} = fixture(), release = customRelease ?? fixtureRelease;
  const cacheMaps = new Map(), requests = [], listeners = new Map(), activations = [];
  const controls = {offline: false, corrupt: null, failPath: null, failCommit: false, releaseChanged: false};
  const cacheObjects = new Map();
  const caches = {
    async keys() { return [...cacheMaps.keys()]; },
    async delete(name) { cacheObjects.delete(name); return cacheMaps.delete(name); },
    async open(name) {
      if (!cacheMaps.has(name)) cacheMaps.set(name, new Map());
      if (!cacheObjects.has(name)) {
        const rows = cacheMaps.get(name);
        cacheObjects.set(name, {
          async match(request) { return rows.get(key(request))?.clone(); },
          async put(request, response) {
            if (controls.failCommit && name.startsWith('personality-v2-') && !name.includes(':staging:')) throw new Error('Quota exceeded during commit');
            rows.set(key(request), response.clone());
          },
          async delete(request) { return rows.delete(key(request)); },
          async keys() { return [...rows.keys()].map(url => new Request(url)); },
        });
      }
      return cacheObjects.get(name);
    },
  };
  async function fetch(request) {
    const url = new URL(key(request));
    requests.push({url: url.href, credentials: request.credentials, cache: request.cache, referrerPolicy: request.referrerPolicy});
    if (controls.offline || controls.failPath === url.pathname) throw new Error('Network unavailable');
    if (url.pathname === ROOT + 'release.mjs') return new Response(releaseSource(release) + (controls.releaseChanged ? '\n' : ''), {headers: {'Content-Type': 'text/javascript'}});
    if (url.pathname.startsWith(ROOT) || url.pathname.startsWith(LEGACY_ROOT)) {
      const body = bytes.get(url.pathname);
      if (!body) return new Response('Not found', {status: 404});
      return new Response(controls.corrupt === url.pathname ? Buffer.from('wrong bytes') : body, {headers: {'Content-Type': 'application/octet-stream'}});
    }
    if (ROUTES.includes(url.pathname)) return new Response(`<html>Public shell: ${url.pathname}${url.search}</html>`, {headers: {'Content-Type': 'text/html; charset=utf-8'}});
    return new Response('Other public page');
  }
  const context = vm.createContext({
    __release: release, __ai: AI_CACHE, __releaseSource: releaseSource, crypto: webcrypto, URL, Request, Response, TextEncoder, Uint8Array,
    caches, fetch, console,
    self: {location: {origin: ORIGIN}, addEventListener: (type, listener) => listeners.set(type, listener),
      skipWaiting: async () => { activations.push('skipWaiting'); }, clients: {claim: async () => {}}},
  });
  assert(workerSource.startsWith("import {RELEASE} from '/assets/personality/v2/release.mjs';"));
  vm.runInContext(workerSource.replace(/^import[^\n]+\n/, 'const RELEASE = __release;\n').replace(/^import \{AI_CACHE\}[^\n]+\n/m,'const AI_CACHE = __ai;\n').replace(/^import \{releaseSource\}[^\n]+\n/m, 'const releaseSource = __releaseSource;\n'), context, {filename: 'personality-worker.js'});
  const digest = sha(JSON.stringify(release));
  async function lifecycle(type) {
    let promise;
    listeners.get(type)({waitUntil(value) { promise = value; }});
    await promise;
  }
  async function install({source = ORIGIN + '/personality/library', requestedDigest = digest} = {}) {
    const messages = []; let promise;
    listeners.get('message')({data: {type: 'INSTALL_RELEASE', releaseDigest: requestedDigest}, source: {url: source},
      ports: [{postMessage(message) { messages.push(message); }}], waitUntil(value) { promise = value; }});
    await promise;
    return messages;
  }
  async function dispatch(url, {mode = 'navigate', method = 'GET'} = {}) {
    let result;
    listeners.get('fetch')({request: {url: new URL(url, ORIGIN).href, method, mode}, respondWith(value) { result = value; }});
    return result ? await result : undefined;
  }
  return {context, cacheMaps, caches, requests, controls, release, digest, lifecycle, install, dispatch, activations};
}

test('install and activation do not preload files or alter unrelated caches', async () => {
  const env = environment();
  const root = await env.caches.open('engmanager-v5'); await root.put('/offline.html', new Response('blog offline'));
  await env.lifecycle('install'); await env.lifecycle('activate');
  assert.equal(env.requests.length, 0);
  assert.equal(env.activations.length, 0, 'An update must not evict the current worker before explicit installation.');
  assert.deepEqual(await env.caches.keys(), ['engmanager-v5']);
});

